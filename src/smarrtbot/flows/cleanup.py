"""Cleanup candidates inside the torrents and media space, and their guarded execution.

Categories:
* ``orphans``: files in torrents/ with link count 1 that no torrent in qBittorrent owns
  (deleted by the guarded filesystem delete, torrents/ only);
* ``unlinked_torrents``: completed torrents with no file hardlinked into the library
  (deleted through the qBittorrent API, with their files);
* ``suspicious``: executables/disc images, or archives named like episodes;
* ``duplicates``: movie folders holding more than one video file (report only: media is
  deleted only through Radarr/Sonarr);
* ``largest``: the biggest titles (deleted through the normal delete flow).

Candidate ids are generated by code. ``propose_cleanup`` only accepts ids from the latest
listing, and execution re-validates every item before touching it.
"""

from __future__ import annotations

import hashlib
import logging
import os
import re
import time
from dataclasses import asdict, dataclass
from typing import Any, Literal

from smarrtbot.flows.actions import Proposal
from smarrtbot.flows.delete import check_limits
from smarrtbot.flows.library import largest, library
from smarrtbot.fsguard import PathRefused
from smarrtbot.util import human_bytes, untrusted

log = logging.getLogger(__name__)

Category = Literal["orphans", "unlinked_torrents", "suspicious", "duplicates", "largest"]
CATEGORIES: tuple[Category, ...] = (
    "orphans",
    "unlinked_torrents",
    "suspicious",
    "duplicates",
    "largest",
)
Action = Literal["fs_delete", "qbit_delete", "title_delete", "report_only"]

VIDEO_EXT = {".mkv", ".mp4", ".avi", ".m4v", ".ts", ".mov", ".wmv", ".webm"}
ARCHIVE_EXT = {".rar", ".zip", ".7z"}
EPISODE_RE = re.compile(r"(?i)\bS\d{1,2}E\d{1,3}\b|\b\d{1,2}x\d{2}\b")
CACHE_KEY = "cleanup_candidates"
CACHE_TTL = 3600


class CleanupError(Exception):
    pass


@dataclass
class Candidate:
    id: str
    category: str
    label: str
    size: int
    action: Action
    ref: str  # file path, torrent hash, or "movie:<id>" / "series:<id>"
    note: str = ""

    def as_tool(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "category": self.category,
            "label": untrusted(self.label, 140),
            "size": human_bytes(self.size),
            "can_delete": self.action in ("fs_delete", "qbit_delete"),
            "how": self.action,
            "note": self.note,
        }


def _cid(category: str, ref: str) -> str:
    return hashlib.sha256(f"{category}|{ref}".encode()).hexdigest()[:10]


async def _qbit_index(svc: Any) -> tuple[list[dict[str, Any]], dict[str, set[str]]]:
    """All torrents, plus the mapped file paths each one owns."""
    torrents = await svc.qbit.torrents() if svc.qbit is not None else []
    owned: dict[str, set[str]] = {}
    for t in torrents:
        h = str(t["hash"]).lower()
        save = str(t.get("save_path") or "").rstrip("/")
        owned[h] = {svc.guard.map_path(f"{save}/{f['name']}") for f in await svc.qbit.files(h)}
    return torrents, owned


async def list_candidates(svc: Any, category: str | None = None) -> list[Candidate]:
    if category is not None and category not in CATEGORIES:
        raise CleanupError(f"unknown category {category!r}")
    wanted = set(CATEGORIES) if category is None else {category}
    s = svc.settings.storage
    out: list[Candidate] = []
    needs_scan = wanted & {"orphans", "suspicious", "duplicates", "unlinked_torrents"}
    scan = svc.scanner.result if needs_scan else None
    if needs_scan and scan is None:
        scan = await svc.scanner.refresh()
    torrents, owned = await _qbit_index(svc) if wanted - {"largest", "duplicates"} else ([], {})
    owned_all = set().union(*owned.values()) if owned else set()
    files_by_path = {f.path: f for f in scan.files} if scan else {}
    min_age = time.time() - s.orphan_min_age_minutes * 60
    ignored = tuple(f"/{d}/" for d in s.ignore_dirs)

    if "orphans" in wanted and scan and svc.qbit is not None:
        for f in scan.by_root(s.torrents_root):
            if f.nlink != 1 or f.path in owned_all or f.mtime > min_age:
                continue
            if any(seg in f.path for seg in ignored):
                continue
            rel = f.path[len(s.torrents_root) + 1 :]
            out.append(
                Candidate(_cid("orphans", f.path), "orphans", rel, f.size, "fs_delete", f.path)
            )

    if "unlinked_torrents" in wanted and svc.qbit is not None:
        queue_ids = await _queue_ids(svc)
        for t in torrents:
            h = str(t["hash"]).lower()
            if float(t.get("progress") or 0) < 1.0 or h in queue_ids:
                continue
            paths = owned.get(h, set())
            if not paths:
                continue
            linked = False
            for p in paths:
                sf = files_by_path.get(p)
                if sf is None:
                    try:
                        st = svc.guard.stat_file(p)
                    except PathRefused:
                        linked = True  # unknown: be conservative
                        break
                    if st is None:
                        continue
                    nlink = st.nlink
                else:
                    nlink = sf.nlink
                if nlink > 1:
                    linked = True
                    break
            if not linked:
                out.append(
                    Candidate(
                        _cid("unlinked_torrents", h),
                        "unlinked_torrents",
                        str(t.get("name") or h),
                        int(t.get("size") or 0),
                        "qbit_delete",
                        h,
                        note="not hardlinked into the library",
                    )
                )

    if "suspicious" in wanted and scan:
        for f in scan.files:
            name = os.path.basename(f.path)
            ext = os.path.splitext(name)[1].lower()
            bad = ext in {e.lower() for e in s.suspicious_extensions} or (
                ext in ARCHIVE_EXT and EPISODE_RE.search(name)
            )
            if not bad:
                continue
            in_torrents = f.path.startswith(s.torrents_root.rstrip("/") + "/")
            owner = next((h for h, ps in owned.items() if f.path in ps), None)
            if in_torrents and owner:
                action, ref, note = "qbit_delete", owner, "deletes the whole torrent"
            elif in_torrents and f.nlink == 1:
                action, ref, note = "fs_delete", f.path, ""
            else:
                action, ref, note = (
                    "report_only",
                    f.path,
                    "in the library: remove via Radarr/Sonarr",
                )
            out.append(
                Candidate(_cid("suspicious", f.path), "suspicious", name, f.size, action, ref, note)
            )

    if "duplicates" in wanted and scan:
        by_dir: dict[str, list[Any]] = {}
        for f in scan.by_root(s.movies_root):
            if os.path.splitext(f.path)[1].lower() in VIDEO_EXT and "sample" not in f.path.lower():
                by_dir.setdefault(os.path.dirname(f.path), []).append(f)
        for d, fs in by_dir.items():
            if len(fs) > 1:
                extra = sorted(fs, key=lambda x: -x.size)[1:]
                out.append(
                    Candidate(
                        _cid("duplicates", d),
                        "duplicates",
                        f"{os.path.basename(d)}: {len(fs)} video files",
                        sum(x.size for x in extra),
                        "report_only",
                        d,
                        note="Radarr tracks one file; remove extras via Radarr",
                    )
                )

    if "largest" in wanted:
        for t in largest(await library(svc), 10):
            ref = f"{t.kind}:{t.id}"
            out.append(
                Candidate(_cid("largest", ref), "largest", t.label(), t.size, "title_delete", ref)
            )

    out.sort(key=lambda c: (CATEGORIES.index(c.category), -c.size))  # type: ignore[arg-type]
    cached = svc.db.kv_get(CACHE_KEY, {"ts": 0, "items": {}})
    if time.time() - cached.get("ts", 0) > CACHE_TTL:
        cached = {"ts": time.time(), "items": {}}
    cached["items"].update({c.id: asdict(c) for c in out})
    svc.db.kv_set(CACHE_KEY, cached)
    return out


async def _queue_ids(svc: Any) -> set[str]:
    ids: set[str] = set()
    for app in (svc.radarr, svc.sonarr):
        if app is None:
            continue
        for q in await app.queue():
            if q.get("downloadId"):
                ids.add(str(q["downloadId"]).lower())
    return ids


def _cached(svc: Any) -> dict[str, Candidate]:
    cached = svc.db.kv_get(CACHE_KEY, {"ts": 0, "items": {}})
    if time.time() - cached.get("ts", 0) > CACHE_TTL:
        return {}
    return {k: Candidate(**v) for k, v in cached["items"].items()}


async def propose_cleanup(svc: Any, ids: list[str], requester_id: int, chat_id: int) -> Proposal:
    known = _cached(svc)
    if not ids:
        raise CleanupError("no candidate ids given")
    picked: list[Candidate] = []
    for i in dict.fromkeys(str(x) for x in ids):
        c = known.get(i)
        if c is None:
            raise CleanupError(f"unknown or expired candidate id {i!r}; list candidates again")
        if c.action == "title_delete":
            raise CleanupError(f"{c.id} is a library title: use delete_title for it")
        if c.action == "report_only":
            raise CleanupError(f"{c.id} can only be reported, not deleted by the bot")
        picked.append(c)
    total = sum(c.size for c in picked)
    refusal = check_limits(svc, requester_id, total, action="cleanup")
    if refusal:
        raise CleanupError(refusal)
    payload = {"items": [asdict(c) for c in picked], "total": total}
    nonce = svc.pending.create("cleanup", requester_id, chat_id, payload)
    return Proposal(
        nonce=nonce,
        kind="cleanup",
        label=f"{len(picked)} item(s)",
        size=total,
        details=[f"item:{c.category}:{c.size}:{untrusted(c.label, 80)}" for c in picked[:15]],
        summary={
            "status": "awaiting_user_confirmation",
            "items": [c.as_tool() for c in picked],
            "total": human_bytes(total),
        },
    )


@dataclass
class CleanupResult:
    dry_run: bool
    deleted: list[tuple[str, int]]
    skipped: list[tuple[str, str]]
    freed: int


async def execute_cleanup(
    svc: Any, payload: dict[str, Any], user_id: int, dry_run: bool
) -> CleanupResult:
    items = [Candidate(**c) for c in payload["items"]]
    refusal = check_limits(svc, user_id, int(payload["total"]), action="cleanup")
    if refusal:
        raise CleanupError(refusal)
    _, owned = await _qbit_index(svc) if svc.qbit is not None else ([], {})
    owned_all = set().union(*owned.values()) if owned else set()
    queue_ids = await _queue_ids(svc)
    res = CleanupResult(dry_run, [], [], 0)
    hashes: list[tuple[Candidate, int]] = []
    for c in items:
        try:
            if c.action == "fs_delete":
                if c.ref in owned_all:
                    raise PathRefused("now owned by a torrent")
                freed = svc.guard.delete_file(
                    c.ref, require_single_link=True, expect_size=c.size, dry_run=dry_run
                )
                res.deleted.append((c.label, c.size))
                res.freed += freed
            elif c.action == "qbit_delete":
                if c.ref not in owned:
                    raise PathRefused("torrent no longer exists")
                if c.ref in queue_ids:
                    raise PathRefused("torrent is in the download queue")
                single = 0
                for p in owned[c.ref]:
                    st = svc.guard.stat_file(p)
                    if st is None:
                        continue
                    if c.category == "unlinked_torrents" and st.nlink > 1:
                        raise PathRefused("a file is now hardlinked into the library")
                    if st.nlink == 1:
                        single += st.size
                hashes.append((c, single))
            else:
                raise PathRefused("not deletable")
        except (PathRefused, FileNotFoundError) as exc:
            res.skipped.append((c.label, str(exc)))
    if hashes:
        if not dry_run:
            await svc.qbit.delete([c.ref for c, _ in hashes], delete_files=True)
        for c, single in hashes:
            res.deleted.append((c.label, c.size))
            if not dry_run:
                res.freed += single  # hardlinked files stay in the library, so they free nothing
    svc.db.audit(
        user_id,
        "cleanup",
        f"{len(res.deleted)} item(s)",
        res.freed,
        dry_run,
        {"deleted": res.deleted[:50], "skipped": res.skipped[:50]},
    )
    return res
